import assert from 'node:assert/strict';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { loadAuthority } from '../src/compare/production-authority.js';
import { sealFencedArchiveFiles,validateFencedArchiveFile } from '../src/compare/poly2-fenced-archive.js';
import { compare } from '../src/compare/phase4.js';
const dir=process.argv[2]!;
const external=loadAuthority(join(dir,'authority.json'),readFileSync(join(dir,'pin'),'utf8'));
const binding=external.authority.binding;
const path=join(dir,'archive.json');
sealFencedArchiveFiles(binding,join(dir,'fence.ndjson'),join(dir,'drain.ndjson'),path,external);
const archive=validateFencedArchiveFile(path,binding.cohort,binding.window,false,external);
assert.deepEqual(archive.rows.map(r=>r.sourceRecordId),[1]);
assert.equal(archive.rows[0]!.normalizedUtc,null);
assert.equal(archive.rows[0]!.ingestedUtc,'2026-01-01T12:00:00.000001Z');
assert.equal(archive.rows[0]!.decisionUtc,'2026-01-03T00:01:00.000001Z');
mkdirSync(join(dir,'shadow'));writeFileSync(join(dir,'cohorts.json'),JSON.stringify({window:binding.window,controlled:binding.cohort}));
const p=spawnSync('node',['--import','tsx','src/compare/cli.ts',join(dir,'shadow'),path,join(dir,'cohorts.json'),join(dir,'out'),join(dir,'authority.json'),external.pin],{cwd:process.cwd(),encoding:'utf8'});
assert.equal(p.status,0,p.stdout+p.stderr);
const result=JSON.parse(readFileSync(join(dir,'out/comparison.json'),'utf8'));
assert.deepEqual(result,compare(archive,new Map(),binding.window,w=>binding.cohort.includes(w)?'CONTROLLED_OVERLAP':null,new Map()));
console.log(JSON.stringify({custody:'DISPOSABLE_OBSERVATIONAL_NATIVE',rowCount:archive.rows.length,productionCLIExit:p.status,primary:result.coverage.poly2Only,authority:external.pin}));
